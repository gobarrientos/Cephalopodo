pub fn build_landmark_map(
    placed: &[PlacedLandmark],
    image_width: f64,
    image_height: f64,
) -> HashMap<String, Point2D> {
    let mut map = HashMap::new();
    for def in get_landmark_catalog() {
        map.insert(
            def.id.clone(),
            Point2D::new(def.default_norm_x * image_width, def.default_norm_y * image_height),
        );
    }
    for p in placed {
        let cid = canonicalize_landmark_id(&p.id);
        map.insert(cid, Point2D::new(p.x, p.y));
    }
    map
}
