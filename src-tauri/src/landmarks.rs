#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LandmarkDefinition {
    pub id: String,
    pub aliases: Vec<String>,
    pub name_es: String,
    pub name_en: String,
    pub category: String, // "cranial", "maxilla", "mandible", "dental", "soft_tissue", "airway_cervical", "delaire", "frontal_pa"
    pub view_type: String, // "lateral", "frontal", "opg"
    pub default_norm_x: f64,
    pub default_norm_y: f64,
    pub description_es: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlacedLandmark {
    pub id: String,
    pub x: f64,
    pub y: f64,
    pub confidence: f64,
    pub source: String, // "manual", "ai_onnx", "ai_vision", "delaire_xml"
}

/// Normalizes a landmark identifier using `CorrespondancesPoint.txt` from `Delaire Evolution`
/// and standard international cephalometric synonyms (`alexcorvi/cephalometric`, `CEPHOSS`, `Aariz`).
pub fn canonicalize_landmark_id(raw: &str) -> String {
    match raw.trim() {
        "PTi" | "Pti" => "Pti".to_string(),
        "PTs" | "Pts" => "Pts".to_string(),
        "GO" | "Go" => "Go".to_string(),
        "NP" | "Np" => "Np".to_string(),
        "Sy.p" | "Syp" => "Syp".to_string(),
        "ocl.p" | "oclps" | "OccPost" => "OccPost".to_string(),
        "ocl.a" | "oclas" | "OccAnt" => "OccAnt".to_string(),
        "Hy" | "Hys" | "H" | "Hya" => "H".to_string(),
        "ANS" | "ENA" => "ENA".to_string(),
        "PNS" | "ENP" => "ENP".to_string(),
        "U1i" | "Ib" | "Is" => "U1i".to_string(),
        "U1a" | "Ia" | "Isa" => "U1a".to_string(),
        "L1i" | "ib" | "Ii" => "L1i".to_string(),
        "L1a" | "ia" | "Iia" => "L1a".to_string(),
        "Help_Pog" | "Pg" | "Pog" => "Pog".to_string(),
        "Help_Clp" | "Clp" => "Clp".to_string(),
        "Pog.c" | "Pog'" => "Pog'".to_string(),
        "Nez" | "Prn" => "Prn".to_string(),
        "Ss.N" | "Sn" => "Sn".to_string(),
        other => other.to_string(),
    }
}

